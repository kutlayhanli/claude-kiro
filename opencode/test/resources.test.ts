import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { RESOURCES, materializeResources } from "../src/resources.ts";

const PACKAGE_ROOT = join(import.meta.dirname, "..");

test("both resources are materialized under the project with OpenCode names", () => {
  const dir = mkdtempSync(join(tmpdir(), "ck-resources-"));
  try {
    const written = materializeResources(dir, PACKAGE_ROOT);
    assert.equal(written.length, 2);
    assert.deepEqual(
      written.map((path) => path.split("/").pop()).sort(),
      RESOURCES.map((resource) => resource.file).sort(),
    );

    const fallback = readFileSync(join(dir, ".opencode", "ck", "without-workflow-tool.md"), "utf8");
    assert.match(fallback, /^<!-- Generated by opencode-claude-kiro/);
    assert.match(fallback, /subagent tool/);
    assert.match(fallback, /ck-implementer/);
    assert.doesNotMatch(fallback, /spec:implementer|subagent_type|AskUserQuestion|TodoWrite/);
    assert.doesNotMatch(fallback, /\$\{CLAUDE_PLUGIN_ROOT\}/);

    const brief = readFileSync(join(dir, ".opencode", "ck", "spec-implement-brief.md"), "utf8");
    assert.match(brief, /webfetch/);
    assert.doesNotMatch(brief, /WebFetch|Claude Code/);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
