/**
 * The two resources the skill text points at must be readable by an OpenCode agent in the project, with
 * OpenCode tool names. The plugin materializes rewritten copies under `.opencode/ck/`.
 */

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { rewriteText } from "./rewrite.ts";

export const RESOURCES: ReadonlyArray<{ file: string; workflowName: string }> = [
  { file: "without-workflow-tool.md", workflowName: "spec:spec-create" },
  { file: "spec-implement-brief.md", workflowName: "spec:spec-implement" },
];

export function materializeResources(projectDir: string, packageRoot: string): string[] {
  const directory = join(projectDir, ".opencode", "ck");
  mkdirSync(directory, { recursive: true });

  const written: string[] = [];
  for (const resource of RESOURCES) {
    const sourcePath = join(packageRoot, "vendor", "resources", resource.file);
    let source: string;
    try {
      source = readFileSync(sourcePath, "utf8");
    } catch {
      throw new Error(`vendor/resources/${resource.file} is missing; run \`npm run sync-vendor\` from opencode/`);
    }
    const body = rewriteText(source, {
      packageRoot,
      projectDir,
      workflowName: resource.workflowName,
    }).trim();
    const header =
      `<!-- Generated by opencode-claude-kiro from vendor/resources/${resource.file}. ` +
      "Do not edit; rerun the plugin instead. -->";
    const path = join(directory, resource.file);
    writeFileSync(path, `${header}\n\n${body}\n`);
    written.push(path);
  }
  return written;
}
